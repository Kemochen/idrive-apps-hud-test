"""Bakes the HUD turn card's lettering into src/card_font.cpp.

    python3 tools/bake_card_font.py --font NotoSans-Regular.ttf > src/card_font.cpp

Two sets of glyphs, each one size, drawn smaller by the card (card_draw.cpp):
the text (street names, the distance's unit) and the digits (the distance,
a roundabout's exit). Each glyph is its coverage, 4 bits a pixel. The text
set is the font's Latin letters (Basic Latin, Latin-1, Latin Extended-A, the
Romanian comma letters) and a few marks, as far as the font has them: a
street name with a letter outside the set is not drawn.

The font is Noto Sans (SIL Open Font License 1.1, LICENSES/OFL-1.1.txt). With
--text-font and --digit-font the two sets come from two files (the Medium
and SemiBold weights the design uses); with one Regular file (--font) the
weights are made by thickening its strokes (--text-bold, --digit-bold, in
quarter pixels a side). Needs Pillow built with FreeType, and fontTools.
"""
import argparse
import sys

from fontTools.ttLib import TTFont
from PIL import Image, ImageDraw, ImageFont

SS = 4                      # each glyph is drawn SS times its size, then averaged down
TEXT_PX, DIGIT_PX = 40, 60  # card_draw.cpp draws at most these sizes
TEXT_RANGES = [(0x20, 0x7E), (0xA0, 0x17F), (0x218, 0x21B), (0x2013, 0x2014), (0x2018, 0x201E), (0x2026, 0x2026)]
DIGITS = "0123456789.,' "


def font_chars(path):
    """The text set's characters the font has."""
    cmap = TTFont(path).getBestCmap()
    return [cp for lo, hi in TEXT_RANGES for cp in range(lo, hi + 1) if cp in cmap]


def bake(path, px, bold, cps):
    font = ImageFont.truetype(path, px * SS)
    pad = 4 * SS + bold
    size = (px * 2 + 8) * SS
    base = (px + px // 2) * SS
    glyphs, pixels = [], bytearray()
    for cp in cps:
        ch = chr(cp)
        img = Image.new('L', (size, size), 0)
        ImageDraw.Draw(img).text((pad, base), ch, font=font, fill=255, anchor='ls', stroke_width=bold, stroke_fill=255)
        small = img.resize((size // SS, size // SS), Image.BOX)
        box = small.point(lambda v: 255 if v >= 9 else 0).getbbox()
        adv = font.getlength(ch) / SS + (1.2 * bold / SS if ch.strip() else 0)
        if not box:
            glyphs.append((cp, len(pixels), 0, 0, 0, 0, adv))
            continue
        crop = small.crop(box)
        w, h = crop.size
        nib = [min(15, (v + 8) // 17) for v in crop.tobytes()]
        if len(nib) % 2:
            nib.append(0)
        off = len(pixels)
        pixels.extend((nib[i] << 4) | nib[i + 1] for i in range(0, len(nib), 2))
        glyphs.append((cp, off, w, h, box[0] - pad // SS, base // SS - box[1], adv))
    return glyphs, pixels


def emit(name, px, glyphs, pixels, out):
    out.write('static const uint8_t %sPixels[] = {' % name)
    for i, b in enumerate(pixels):
        out.write(('\n    ' if i % 24 == 0 else ' ') + '%d,' % b)
    out.write('\n};\n\nstatic const CardGlyph %sGlyphs[] = {\n' % name)
    for cp, off, w, h, left, top, adv in glyphs:
        out.write('    {0x%04X, %d, %d, %d, %d, %d, %d},\n' % (cp, off, w, h, left, top, round(adv * 16)))
    out.write('};\n\nconst CardFont %s = {%d, %d, %sGlyphs, %sPixels};\n\n' % (name, px, len(glyphs), name, name))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--font', help='one file for both sets')
    ap.add_argument('--text-font')
    ap.add_argument('--digit-font')
    ap.add_argument('--text-bold', type=int, default=None, help='strokes thickened, quarter pixels a side')
    ap.add_argument('--digit-bold', type=int, default=None)
    a = ap.parse_args()
    text_font, digit_font = a.text_font or a.font, a.digit_font or a.font
    if not text_font or not digit_font:
        ap.error('--font, or --text-font and --digit-font')
    text_bold = a.text_bold if a.text_bold is not None else (0 if a.text_font else 1)
    digit_bold = a.digit_bold if a.digit_bold is not None else (0 if a.digit_font else 4)
    out = sys.stdout
    out.write('// SPDX-License-Identifier: OFL-1.1\n'
              '// Glyphs of Noto Sans, Copyright 2015-2021 Google LLC, under the SIL Open Font\n'
              '// License 1.1 (LICENSES/OFL-1.1.txt). Generated by tools/bake_card_font.py\n'
              '// (text: strokes +%d, digits: strokes +%d quarter pixels a side); not edited by hand.\n'
              '#include "card_font.h"\n\nnamespace woc {\n\n' % (text_bold, digit_bold))
    emit('kCardText', TEXT_PX, *bake(text_font, TEXT_PX, text_bold, font_chars(text_font)), out)
    emit('kCardDigits', DIGIT_PX, *bake(digit_font, DIGIT_PX, digit_bold, [ord(c) for c in sorted(DIGITS)]), out)
    out.write('}  // namespace woc\n')


if __name__ == '__main__':
    main()
